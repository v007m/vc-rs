import { svelte } from '@sveltejs/vite-plugin-svelte';
import { defineConfig, type Plugin } from 'vite';

// The HTML report's script and style (D169): `pnpm build:report` writes report/report.js and
// report/report.css, which `vc-adapter-reporters` inlines into every report page. Both are
// committed, so the Rust build needs no Node; `mise run report:check` keeps them current.

const banner = 'generated by pnpm build:report; do not edit';

/** What would end the inline script early or switch the HTML parser's script state. */
const unsafe = /<(\/script|!--)/gi;

/**
 * Stamps the banner. In the script, `<` before `/script` or `!--` (Svelte's runtime has a
 * `<!---->` template) becomes `\x3C`, which reads the same in strings, templates and regexes;
 * a stylesheet with either is refused.
 */
function reportOutput(): Plugin {
  return {
    name: 'vib-report-output',
    enforce: 'post',
    generateBundle(_, bundle) {
      for (const file of Object.values(bundle)) {
        if (file.type === 'chunk') {
          file.code = `/* ${banner} */\n${file.code.replace(unsafe, '\\x3C$1')}`;
          continue;
        }
        const text = String(file.source);
        if (unsafe.test(text)) this.error(`${file.fileName} has </script or <!--`);
        file.source = `/* ${banner} */\n${text}`;
      }
    },
  };
}

export default defineConfig({
  plugins: [svelte({ configFile: false }), reportOutput()],
  define: { 'process.env.NODE_ENV': '"production"' },
  publicDir: false,
  build: {
    outDir: 'report',
    emptyOutDir: false,
    target: 'es2022',
    reportCompressedSize: false,
    lib: {
      entry: 'src/report/main.ts',
      name: 'VIB',
      formats: ['iife'],
      fileName: () => 'report.js',
      cssFileName: 'report',
    },
  },
});
