const path = require('path');
const { loadComponent } = require('./load');
const { makeRenderer } = require('./render');
const ART = path.resolve(__dirname, '../vibmock/project/WebAgents.dc.html');
const { Component, timers } = loadComponent(ART);
const r = makeRenderer(ART, path.join(__dirname, 'shots-agents'));
const c = new Component({});
const ev = (value) => ({ target: { value } });
let v = c.renderVals();
r.save('a01-initial', v);
v.toggleSide(); r.save('a02-collapsed', c.renderVals()); c.renderVals().toggleSide();
v = c.renderVals(); v.queue[0].toggleAlways(); v = c.renderVals(); v.queue[1].toggleDeny(); v = c.renderVals(); v.queue[1].setDeny(ev('Keep the fixed total'));
v = c.renderVals(); v.connSteps[0].copy(); r.save('a03-panels-toast', c.renderVals());
timers.flush();
v = c.renderVals(); v.connTabs[1].pick(); v = c.renderVals(); v.log[0].toggle(); v = c.renderVals(); v.log[3].toggle(); r.save('a04-cursor-logopen', c.renderVals());
v = c.renderVals(); v.connTabs[2].pick(); r.save('a05-anyclient', c.renderVals());
v = c.renderVals(); v.queue[0].always(); timers.flush(); v = c.renderVals(); v.queue[0].deny(); timers.flush();
v = c.renderVals(); r.save('a06-resolved', v);
if (!v.queueEmpty) throw new Error('queue not empty');
v.toggleSide(); r.save('a07-resolved-collapsed', c.renderVals()); c.renderVals().toggleSide();
v = c.renderVals(); v.logKinds[1].pick(); v = c.renderVals(); v.setLogAgent(ev('Cursor')); r.save('a08-filtered', c.renderVals());
v = c.renderVals(); v.setLogQ(ev('zzz')); r.save('a09-logempty', c.renderVals());
const errs = r.errors();
console.log(errs.length ? errs.slice(0, 30).join('\n') : 'states ok, holes resolve in every state');
